import assert from "node:assert/strict";
import fs from "node:fs";
import { captureLandingAttribution, getFirstTouchAttribution, setAnalyticsOptOut, trackBookingEvent, trackRoamsteadEvent } from "../src/lib/analytics.ts";
import { BOOKING_EVENTS, captureFirstTouch, hostawayCheckoutHref, isAnalyticsOptedOut, sanitizeAnalyticsEvent } from "../src/lib/booking-analytics.ts";
const local = new Map(), session = new Map();
const store = map => ({ getItem: key => map.get(key), setItem: (key, value) => map.set(key, value), removeItem: key => map.delete(key) });
globalThis.window = { location: { pathname: "/midway", hostname: "roamstead-co.com", search: "?utm_source=first&utm_medium=email&utm_campaign=winter" }, localStorage: store(local), sessionStorage: store(session) };
globalThis.document = { referrer: "" };
Object.defineProperty(globalThis, "navigator", { configurable: true, value: {} });
const first = captureLandingAttribution();
const href = () => hostawayCheckoutHref(455631, "2026-12-01", "2026-12-03", 2, first);
const expected = "https://roamstead_ventures.holidayfuture.com/checkout/455631?start=2026-12-01&end=2026-12-03&numberOfGuests=2";
assert.equal(href(), expected + "&utm_source=first&utm_medium=email&utm_campaign=winter");
assert.ok(local.has("rs_first_touch"));
assert.ok(session.has("rs_booking_attr"));
assert.equal(setAnalyticsOptOut(true), true);
assert.equal(local.get("rs_analytics_optout"), "1");
assert.equal(local.has("rs_first_touch"), false);
assert.equal(session.has("rs_booking_attr"), false);
// Only the choice may be read while opted out, never either attribution record.
window.localStorage.getItem = key => { assert.equal(key, "rs_analytics_optout"); return local.get(key); };
window.sessionStorage.getItem = () => { throw Error("must not read session attribution"); };
assert.deepEqual(captureLandingAttribution(), {});
assert.equal(getFirstTouchAttribution(), null);
assert.equal(captureFirstTouch({ getItem() { assert.fail("first touch read"); } }, window.location), null);
assert.equal(href(), expected, "Even previously captured fields cannot enter checkout while opted out");
trackBookingEvent(BOOKING_EVENTS.pageView, { propertySlug: "granary" });
trackRoamsteadEvent("early_access_submission_accepted");
assert.equal(window.vaq, undefined);
for (const type of ["pageview", "event"]) assert.equal(sanitizeAnalyticsEvent({ type, url: "https://roamstead-co.com/midway" }), null);
assert.equal(local.size, 1);
assert.equal(session.size, 0);
assert.equal(setAnalyticsOptOut(false), false);
window.localStorage = store(local);
window.sessionStorage = store(session);
window.location.pathname = "/properties/granary";
window.location.search = "?utm_source=next";
const next = captureLandingAttribution();
assert.equal(next.utm_source, "next");
assert.notEqual(next.funnel_ref, first.funnel_ref, "In-memory attribution was cleared");
trackBookingEvent(BOOKING_EVENTS.pageView, { propertySlug: "granary" });
trackRoamsteadEvent("early_access_submission_accepted");
assert.equal(window.vaq.filter(entry => entry[0] === "event").length, 2);
assert.ok(sanitizeAnalyticsEvent({ type: "pageview", url: "https://roamstead-co.com/properties/granary" }));
for (const signal of ["globalPrivacyControl", "doNotTrack"]) {
  navigator[signal] = signal === "globalPrivacyControl" ? true : "1";
  assert.equal(getFirstTouchAttribution(), null);
  const before = window.vaq.length;
  trackRoamsteadEvent("early_access_submission_accepted");
  trackBookingEvent(BOOKING_EVENTS.dateCheckAttempt, { propertySlug: "granary" });
  assert.equal(window.vaq.length, before);
  const beforeLocal = [...local], beforeSession = [...session];
  let storageCalls = 0;
  const blockedStore = { getItem() { storageCalls++; throw Error("no reads"); }, setItem() { storageCalls++; throw Error("no writes"); } };
  window.localStorage = blockedStore;
  window.sessionStorage = blockedStore;
  assert.deepEqual(captureLandingAttribution(), {});
  assert.equal(captureFirstTouch(blockedStore, window.location), null);
  assert.equal(getFirstTouchAttribution(), null, "early-access payload has no attribution");
  assert.equal(href(), expected);
  for (const type of ["pageview", "event"]) assert.equal(sanitizeAnalyticsEvent({ type, url: "https://roamstead-co.com/midway" }), null);
  assert.equal(storageCalls, 0, signal + " must not access either store");
  assert.deepEqual([...local], beforeLocal);
  assert.deepEqual([...session], beforeSession);
  window.localStorage = store(local);
  window.sessionStorage = store(session);
  delete navigator[signal];
}
for (const key of ["localStorage", "sessionStorage"]) Object.defineProperty(window, key, { configurable: true, get() { throw Error("blocked"); } });
assert.equal(isAnalyticsOptedOut(), false);
for (const off of [true, false]) assert.doesNotThrow(() => setAnalyticsOptOut(off));
assert.doesNotThrow(() => captureLandingAttribution());
assert.doesNotThrow(() => trackRoamsteadEvent("early_access_submission_accepted"));
assert.doesNotThrow(href);
assert.doesNotThrow(() => sanitizeAnalyticsEvent({ type: "event", url: "https://roamstead-co.com/midway" }));
const page = fs.readFileSync(new URL("../src/app/privacy/page.tsx", import.meta.url), "utf8");
for (const placeholder of ["legal entity name", "privacy contact email", "effective date", "how changes will be announced"]) assert.ok(page.includes(`[OWNER TO CONFIRM: ${placeholder}]`));
assert.doesNotMatch(page, /GDPR|CCPA|compliant/i);
assert.match(page, /canonical: "\/privacy"/);
assert.match(page, /id="choices"/);
console.log("PASS: privacy placeholders, opt-out, capture, sending, sanitizer, checkout, opt-in, signals and blocked storage");
